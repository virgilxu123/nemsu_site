The North Eastern Mindanao State University – San Miguel Campus (NEMSU-SMC) is a premier institution for agriculture and forestry education in Surigao del Sur. Established in 1953 as the Surigao National Agricultural School, the campus has evolved through several legislative transformations into a center of excellence committed to producing competent professionals in agriculture, forestry, education, and allied fields while promoting sustainable development and environmental stewardship. This extensive journey includes its eras as the Tago River Valley Institute of Agriculture, Surigao del Sur Polytechnic College (SSPC), and Surigao del Sur State University (SDSSU) before formally becoming NEMSU in 2021 by virtue of Republic Act No. 11584. Today, under the leadership of University President III Dr. Nemesio G. Loayon and Campus Director Dr. Marvie V. Gonzaga, the institution thrives on a culture of excellence, mutual respect, and continuous progress.

Located in Barangay Carromata, San Miguel, Surigao del Sur, the campus is home to the College of Agriculture and Forestry (Bachelor of Science in Agriculture major in Crop Science and Bachelor of Science in Forestry) and the College of Teacher Education (Bachelor of Technology and Livelihood Education major in Home Economics). Its 789-hectare site—the largest among the NEMSU campuses—includes 389 hectares of lowland farms, 175 hectares of upland areas, and 225 hectares of forest reserves. This vast landscape serves as a living laboratory that supports quality instruction, research, extension, and production. Positioned on a scenic plateau overlooking the province’s biggest lowland rice bowl, the campus provides an inspiring backdrop for hands-on learning. Recognized by the Commission on Higher Education (CHED) as the Provincial Institute of Agriculture and Forestry (PIAF) under the National Agriculture and Fisheries Education System (NAFES), NEMSU–San Miguel plays a vital role in advancing agricultural and forestry education in the region. Its state-of-the-art laboratories prepare students with the knowledge, technical expertise, and values necessary to address contemporary challenges in agriculture, natural resource management, and rural development.

Beyond academics, the campus actively engages with local communities through research, extension services, technology transfer, and collaborative initiatives that promote sustainable farming practices, environmental conservation, and community empowerment. It also serves as a beacon of inclusivity and cultural sensitivity, honoring the rich tapestry of tribal heritage and cultivating unity within the indigenous communities it serves. This holistic growth is supported by essential infrastructure projects from local government units and the congressional district, including a three-story multi-purpose building and Level 2 potable water systems. Guided by its commitment to excellence, innovation, and public service, NEMSU–San Miguel Campus continues to develop globally competitive, socially responsible graduates who contribute to the sustainable growth of Surigao del Sur, the Caraga Region, and beyond.
