The present North Eastern Mindanao State University (NEMSU)–Lianga Campus stands as a testament to a distinguished legacy of educational transformation, visionary leadership, and unwavering commitment to community development. Its origins trace back to 1949, when it was established as Lianga Junior High School through the initiative of Honorable Mayor Prudencio S. Ronquillo, whose vision laid the foundation for accessible secondary education in the municipality. In 1954, the institution was elevated to Lianga High School (LHS), continuing under his dedicated leadership and further strengthening educational opportunities for the youth of Lianga and neighboring communities.

A significant milestone in the institution's history was achieved in 1963, when it was converted into the Lianga National School of Fisheries (LNSF) through Republic Act No. 3528, principally authored by Honorable Congressman Vicente T. Pimentel, Sr. The implementation of the law was spearheaded by Honorable Governor Gregorio P. Murillo, Sr., M.D., marking the institution's transition toward specialized education in fisheries and aquatic resources, aligned with the region's abundant coastal and marine potential.

The institution continued its progressive transformation in 1977 with the establishment of the Surigao del Sur Institute of Fisheries and Aquaculture (SSIFA) through Batas Pambansa Blg. 627, principally sponsored by Assemblyman Jose "Popit" Puyat Jr. This development significantly expanded its mandate in fisheries, aquaculture, and marine resource education, positioning the institution as a key provider of specialized higher education in the province.

In 1992, SSIFA was integrated into the Surigao del Sur Polytechnic College (SSPC) by virtue of Republic Act No. 7377, authored by Honorable Congressman Mario Serra Ty, M.D. This integration broadened the institution's academic scope and strengthened its role in delivering quality tertiary education responsive to the developmental needs of Surigao del Sur.

The institution entered a new era in 2010 when SSPC was converted into Surigao del Sur State University (SDSSU) through Republic Act No. 9998. A decade later, its identity was further elevated with the enactment of Republic Act No. 11584, officially renaming the university as North Eastern Mindanao State University (NEMSU), reflecting its expanded mandate and strategic role in advancing higher education across Northeastern Mindanao.

Nestled in the coastal municipality of Lianga, Surigao del Sur, North Eastern Mindanao State University–Lianga Campus has evolved into a premier institution dedicated to academic excellence, research innovation, extension services, and sustainable community development. As the University's recognized Center for Fisheries and Marine Sciences, the campus plays a pivotal role in advancing fisheries education, marine biodiversity conservation, coastal resource management, and environmental stewardship throughout the Caraga Region. Building upon its rich heritage as the former Surigao del Sur Institute of Fisheries and Aquaculture, the campus embodies a tradition of resilience, innovation, and public service that continues to shape its institutional identity.

Today, NEMSU–Lianga Campus offers a diverse portfolio of undergraduate and graduate programs in Fisheries, Marine Biology, Environmental Science, Teacher Education, Computer Science, Business Administration, and Hospitality Management. Guided by its commitment to producing competent, ethical, socially responsible, and globally competitive graduates, the campus integrates transformative instruction with impactful research, responsive extension programs, and innovation initiatives that address both local priorities and global challenges. Its academic programs are continually strengthened through quality assurance mechanisms, accreditation, curriculum enhancement, faculty development, and industry-responsive learning experiences.

The campus has earned regional and national distinction for its significant contributions to fisheries education, marine science, and sustainable coastal development. It has been designated by the Commission on Higher Education (CHED) as the National University/College of Fisheries (NUCAF) for the Caraga Region under the National Agriculture and Fisheries Education System (NAFES), affirming its leadership in specialized instruction, research, extension, and innovation in fisheries and aquatic sciences. Through externally funded research projects and community-based extension initiatives, the campus actively promotes sustainable fisheries management, aquaculture development, seaweed production, marine biodiversity conservation, mangrove rehabilitation, climate resilience, and environmental protection, generating meaningful impact on coastal communities and resource-dependent livelihoods.

